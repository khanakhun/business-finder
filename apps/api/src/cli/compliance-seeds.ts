// node src/cli/compliance-seeds.ts > <migration>.sql
// The seeded compliance data as SQL (BF-049): every policy file (seeds/policies/*.json, validated) as version 1 of its
// global seed, and the offer ↔ category relevance. Seeds live in git as JSON and reach databases through a migration;
// a change to a policy is a new version in a new migration, never an edit of a migrated one.
import { readdirSync, readFileSync } from 'node:fs';
import { newId, OfferSchema, PolicySeedSchema } from '@bf/contracts';
import { z } from 'zod';

const DIR = new URL('../modules/compliance/infrastructure/seeds/', import.meta.url);

const literal = (value: string) => `'${value.replace(/'/g, "''")}'`;
const json = (value: unknown) => `${literal(JSON.stringify(value))}::jsonb`;

const lines: string[] = [
  '-- BF-049: seeded compliance policies (needs_legal_review) and offer relevance. Generated by src/cli/compliance-seeds.ts.',
];
const files = readdirSync(new URL('policies/', DIR))
  .filter((name) => name.endsWith('.json'))
  .sort();
for (const file of files) {
  const seed = PolicySeedSchema.parse(JSON.parse(readFileSync(new URL(`policies/${file}`, DIR), 'utf8')));
  const [name, channel] = file.replace(/\.json$/, '').split('.');
  if ((name === 'ANY' ? '*' : name) !== seed.jurisdiction || channel !== seed.channel)
    throw new Error(`${file}: says ${seed.jurisdiction}/${seed.channel}`);
  lines.push(
    `INSERT INTO "compliance_policies" ("id", "organization_id", "jurisdiction", "channel", "version", "kind", "rules", "sources", "note", "needs_legal_review") VALUES (${literal(newId())}, NULL, ${literal(seed.jurisdiction)}, ${literal(seed.channel)}, 1, 'seed', ${json(seed.policy)}, ${json(seed.sources)}, ${seed.note ? literal(seed.note) : 'NULL'}, true) ON CONFLICT DO NOTHING;`,
    '--> statement-breakpoint',
  );
}
const Relevance = z.array(
  z.object({
    offer: OfferSchema,
    taxonomyPrefix: z.string().max(120),
    relevant: z.boolean(),
    rationale: z.object({ en: z.string().min(1), fr: z.string().min(1) }),
  }),
);
const relevance = Relevance.parse(JSON.parse(readFileSync(new URL('offer-relevance.json', DIR), 'utf8')));
for (const [position, row] of relevance.entries()) {
  lines.push(
    `INSERT INTO "offer_relevance" ("id", "offer", "taxonomy_prefix", "relevant", "rationale", "position") VALUES (${literal(newId())}, ${literal(row.offer)}, ${literal(row.taxonomyPrefix)}, ${row.relevant}, ${json(row.rationale)}, ${position}) ON CONFLICT DO NOTHING;`,
    '--> statement-breakpoint',
  );
}
lines.pop();
process.stdout.write(`${lines.join('\n')}\n`);
console.error(`${files.length} policies, ${relevance.length} relevance rows`);
