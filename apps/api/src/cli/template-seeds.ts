// node src/cli/template-seeds.ts > <migration>.sql
// The seeded email templates as SQL (BF-051): every file in seeds/templates/{en,fr}/ (validated and linted: any lint
// error fails) as version 1 of a global template (no workspace). A change to a seed is a new version in a new
// migration, never an edit of a migrated one.
import { readdirSync, readFileSync } from 'node:fs';
import { EmailLocaleSchema, EmailPurposeSchema, newId, OfferSchema } from '@bf/contracts';
import { z } from 'zod';
import { lintTemplate } from '../modules/outreach/domain/drafting/template-lint.ts';

const DIR = new URL('../modules/outreach/infrastructure/drafting/seeds/templates/', import.meta.url);

const Seed = z.object({
  key: z.string().regex(/^[a-z0-9_]+$/),
  name: z.string().min(2).max(120),
  purpose: EmailPurposeSchema,
  offer: OfferSchema,
  locale: EmailLocaleSchema,
  subjectVariants: z.array(z.string().min(3).max(150)).min(1).max(5),
  bodyMd: z.string().min(10).max(5000),
});

const literal = (value: string) => `'${value.replace(/'/g, "''")}'`;
const array = (values: readonly string[]) => `ARRAY[${values.map(literal).join(', ')}]::text[]`;

const lines = ['-- BF-051: seeded email templates (EN/FR). Generated by src/cli/template-seeds.ts.'];
for (const locale of ['en', 'fr'] as const) {
  for (const file of readdirSync(new URL(`${locale}/`, DIR))
    .filter((name) => name.endsWith('.json'))
    .sort()) {
    const seed = Seed.parse(JSON.parse(readFileSync(new URL(`${locale}/${file}`, DIR), 'utf8')));
    if (seed.locale !== locale || `${seed.key}.json` !== file)
      throw new Error(`${locale}/${file}: key or locale mismatch`);
    const { issues, variables } = lintTemplate({
      subjects: seed.subjectVariants,
      body: seed.bodyMd,
      purpose: seed.purpose,
      locale,
      template: true,
    });
    const errors = issues.filter((issue) => issue.severity === 'error');
    if (errors.length > 0) throw new Error(`${locale}/${file}: ${errors.map((e) => e.message).join('; ')}`);
    lines.push(
      `INSERT INTO "email_templates" ("id", "organization_id", "key", "name", "purpose", "offer", "locale", "version", "subject_variants", "body_md", "variables", "status", "seeded", "lint") VALUES (${literal(newId())}, NULL, ${literal(seed.key)}, ${literal(seed.name)}, ${literal(seed.purpose)}, ${literal(seed.offer)}, ${literal(locale)}, 1, ${array(seed.subjectVariants)}, ${literal(seed.bodyMd)}, ${array(variables)}, 'active', true, ${literal(JSON.stringify(issues))}::jsonb) ON CONFLICT DO NOTHING;`,
      '--> statement-breakpoint',
    );
  }
}
lines.pop();
process.stdout.write(`${lines.join('\n')}\n`);
