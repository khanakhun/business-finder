import type { Clock } from '@bf/contracts';
import type { Logger } from '@bf/observability';
import { Inject, Injectable, Optional } from '@nestjs/common';
import { CLOCK } from '../../platform/clock/clock.module.ts';
import { queuePriority } from '../domain/batch.ts';
import { GenerationRunner } from './generation.runner.ts';
import {
  type ArtifactStore,
  ENGINE_REGISTRY,
  type EngineRegistry,
  EVENT_STREAM,
  type EventStream,
  GENERATION_ARTIFACTS,
  GENERATION_LIMITS,
  GENERATION_QUEUES,
  GENERATION_REPOSITORY,
  type GenerationLimits,
  type GenerationQueues,
  type GenerationRepository,
  QUALITY_PIPELINE,
  type QualityPipeline,
  SITE_HAND_OFF,
  type SiteHandOff,
} from './ports.ts';
import { JobTransitions } from './transitions.ts';

// After an attempt (BF-039): the quality pipeline judges its site. A pass becomes a site version (author
// `generation_job`) and, when the batch says so, a published preview; issues with repairs left start a repair
// attempt on the same engine; otherwise the version is kept unpublished for a person to review. The reaper fails the
// attempts whose worker died (no heartbeat for a while) so the failover policy applies, and trims the event log.

/** Repairs per job (ARCHITECTURE §11: the repair loop runs at most twice). */
export const MAX_REPAIRS = 2;
/** Events are kept 90 days. */
const EVENT_RETENTION_MS = 90 * 24 * 3600 * 1000;

@Injectable()
export class GenerationQuality {
  constructor(
    @Inject(GENERATION_REPOSITORY) private readonly repository: GenerationRepository,
    @Inject(ENGINE_REGISTRY) private readonly engines: EngineRegistry,
    @Inject(GENERATION_QUEUES) private readonly queues: GenerationQueues,
    @Inject(GENERATION_ARTIFACTS) private readonly artifacts: ArtifactStore,
    @Inject(QUALITY_PIPELINE) private readonly pipeline: QualityPipeline,
    @Inject(SITE_HAND_OFF) private readonly sites: SiteHandOff,
    @Inject(GENERATION_LIMITS) private readonly limits: GenerationLimits,
    @Inject(CLOCK) private readonly clock: Clock,
    private readonly transitions: JobTransitions,
    private readonly runner: GenerationRunner,
    @Optional() @Inject(EVENT_STREAM) private readonly stream?: EventStream | null,
  ) {}

  async evaluate(
    jobId: string,
    attemptId: string,
    logger: Logger,
  ): Promise<'succeeded' | 'repairing' | 'needs_review' | 'skipped' | 'failed'> {
    const job = await this.repository.jobById(jobId);
    const attempt = await this.repository.attemptById(attemptId);
    if (!job || job.status !== 'validating' || !attempt?.specRef) return 'skipped';
    const body = await this.artifacts.get(attempt.specRef);
    let spec: unknown;
    try {
      spec = body ? JSON.parse(body.toString('utf8')) : undefined;
    } catch {
      spec = undefined;
    }
    if (!spec || typeof spec !== 'object') {
      await this.runner.settle(
        job,
        null,
        { code: 'INVALID_OUTPUT', message: 'The site spec cannot be read', retryable: true },
        logger,
      );
      return 'failed';
    }
    const attempts = await this.repository.attempts(job.id);
    const repairs = attempts.filter((candidate) => candidate.mode === 'repair').length;
    const engine = this.engines.get(job.engineCurrent);
    const result = await this.pipeline.evaluate({
      job,
      spec,
      repairsLeft: MAX_REPAIRS - repairs,
      supportsRepair: engine?.capabilities.supportsRepair ?? false,
    });
    const verdict = {
      type: 'log' as const,
      level: result.outcome === 'pass' ? ('info' as const) : ('warn' as const),
      message: `Quality ${result.outcome} (score ${result.score})`,
    };
    const [seq] = await this.repository.appendEvents(job.id, attemptId, [verdict]);
    // Live clients see it before the status that follows.
    if (seq !== undefined)
      await this.stream?.publish(job.id, [{ seq, event: verdict }]).catch(() => undefined);

    if (result.outcome === 'repair') {
      await this.transitions.move(job.id, 'repairing', { qualityScore: result.score });
      await this.queues.run(job.engineCurrent, {
        jobId: job.id,
        attemptNo: job.attemptCount + 1,
        priority: queuePriority(job.priority, job.position),
      });
      return 'repairing';
    }

    const batch = await this.repository.batchById(job.batchId);
    const actor = { organizationId: job.organizationId, userId: batch?.createdBy ?? null };
    let created: { siteId: string; versionId: string };
    try {
      created = await this.sites.createVersion({
        ...actor,
        businessId: job.businessId,
        siteId: job.siteId,
        spec: spec as Record<string, unknown>,
        jobId: job.id,
        changeSummary: `Generated by ${job.engineCurrent} (attempt ${attempt.attemptNo})`,
      });
    } catch (error) {
      // The sites module refused the spec (its own checks are stricter than a draft's): a person reviews.
      logger.warn({ jobId, err: error }, 'generated site refused by the sites module');
      await this.transitions.move(job.id, 'needs_review', {
        qualityScore: result.score,
        errorCode: 'SPEC_REFUSED',
        errorMessage: error instanceof Error ? error.message.slice(0, 500) : 'The site was refused',
      });
      await this.transitions.dispatch(job.batchId);
      return 'needs_review';
    }
    if (result.outcome === 'needs_review') {
      await this.transitions.move(job.id, 'needs_review', {
        siteId: created.siteId,
        resultVersionId: created.versionId,
        qualityScore: result.score,
        errorCode: 'QUALITY_GATES',
        errorMessage: `${result.issues.length} problem(s) left after ${repairs} repair(s)`,
      });
      await this.transitions.dispatch(job.batchId);
      return 'needs_review';
    }
    const publishedUrl = batch?.settings.autoPublishPreview
      ? await this.sites
          .publishPreview({ ...actor, siteId: created.siteId, versionId: created.versionId })
          .catch((error: unknown) => {
            logger.warn({ jobId, err: error }, 'preview not published');
            return null;
          })
      : null;
    await this.transitions.move(job.id, 'succeeded', {
      siteId: created.siteId,
      resultVersionId: created.versionId,
      publishedUrl,
      qualityScore: result.score,
    });
    await this.transitions.dispatch(job.batchId);
    return 'succeeded';
  }

  /** The reaper: attempts without a heartbeat for too long are failed (the failover policy applies); old events go. */
  async reap(logger: Logger): Promise<{ readonly reaped: number; readonly events: number }> {
    const now = this.clock.now();
    const stale = await this.repository.staleAttempts(
      new Date(now.getTime() - this.limits.heartbeatTimeoutMs),
      100,
    );
    let reaped = 0;
    for (const attempt of stale) {
      const job = await this.repository.jobById(attempt.jobId);
      if (!job) continue;
      const outcome = await this.runner.settle(
        job,
        attempt,
        { code: 'HEARTBEAT_LOST', message: 'The worker stopped answering', retryable: true },
        logger,
      );
      if (outcome !== 'skipped') reaped++;
    }
    const events = await this.repository.deleteEventsBefore(
      new Date(now.getTime() - EVENT_RETENTION_MS),
      5_000,
    );
    return { reaped, events };
  }
}
