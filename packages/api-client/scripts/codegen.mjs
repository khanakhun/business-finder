#!/usr/bin/env node
// Generates src/schema.d.ts from openapi.json (written by `pnpm api:openapi`). --check fails when stale (CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC = new URL('../openapi.json', import.meta.url);
const OUT = fileURLToPath(new URL('../src/schema.d.ts', import.meta.url));
const HEADER = '// Generated by `pnpm api:codegen` from openapi.json — do not edit.\n\n';

const ast = await openapiTS(JSON.parse(readFileSync(SPEC, 'utf8')), { exportType: true, alphabetize: true });
const next = HEADER + astToString(ast);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== next) {
    console.error('packages/api-client/src/schema.d.ts is stale. Run: pnpm api:codegen');
    process.exit(1);
  }
  console.log('API client types are up to date.');
} else {
  writeFileSync(OUT, next);
  console.log(`Wrote ${OUT}`);
}
