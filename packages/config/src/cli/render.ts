/** Variables `pnpm infra:up` writes to `.env.generated` (checked against scripts/infra/stack.mjs by its tests). */
export const GENERATED_BY_INFRA: ReadonlySet<string> = new Set([
  'DATABASE_URL',
  'SITES_DATABASE_URL',
  'VALKEY_URL',
  'S3_ENDPOINT',
  'S3_ACCESS_KEY_ID',
  'S3_SECRET_ACCESS_KEY',
  'SMTP_URL',
  'OTEL_EXPORTER_OTLP_ENDPOINT',
  'APP_URL',
  'API_URL',
  'INTEL_URL',
  'NEXT_PUBLIC_API_URL',
  'NEXT_PUBLIC_APP_URL',
  'WEB_PORT',
  'SITES_PORT',
  'SITES_INTERNAL_URL',
  'API_PORT',
  'INTEL_PORT',
  'WORKER_METRICS_PORT',
]);

const GROUPS: ReadonlyArray<readonly [string, EnvSchema]> = [
  ['Core', coreEnv],
  ['Database', z.object({ ...dbEnv.shape, ...sitesDbEnv.shape })],
  ['Valkey', valkeyEnv],
  ['Object storage (S3)', s3Env],
  ['AI providers', aiEnv],
  ['Provider keys (workspace fallback)', providersEnv],
  ['Auth & secrets', authEnv],
  ['System mail', mailEnv],
  ['Intel service', intelEnv],
  ['Sites', sitesApiEnv],
  ['Feature flags', featureFlagsEnv],
];

export interface DocumentedVariable extends VariableInfo {
  readonly group: string;
  readonly apps: readonly AppName[];
  readonly generated: boolean;
}

/** Every declared variable once, grouped, with the apps that read it. */
export function collectVariables(): DocumentedVariable[] {
  const apps = new Map<string, AppName[]>();
  const infos = new Map<string, VariableInfo>();
  for (const [app, schema] of Object.entries(APP_SCHEMAS) as [AppName, EnvSchema][]) {
    for (const info of describeVariables(schema)) {
      apps.set(info.name, [...(apps.get(info.name) ?? []), app]);
      if (!infos.has(info.name)) infos.set(info.name, info);
    }
  }
  const groupOf = new Map<string, string>();
  for (const [group, schema] of GROUPS)
    for (const name of Object.keys(schema.shape)) groupOf.set(name, group);

  const groupOrder = [...GROUPS.map(([g]) => g), 'App-specific'];
  return [...infos.values()]
    .map((info) => ({
      ...info,
      group: groupOf.get(info.name) ?? 'App-specific',
      apps: apps.get(info.name) ?? [],
      generated: GENERATED_BY_INFRA.has(info.name),
    }))
    .sort((a, b) => groupOrder.indexOf(a.group) - groupOrder.indexOf(b.group));
}

const DOC_START = '<!-- env:start (generated by `pnpm env:doc`, do not edit) -->';
const DOC_END = '<!-- env:end -->';

export function renderDocTable(variables: readonly DocumentedVariable[]): string {
  const escapePipes = (text: string) => text.replaceAll('|', '\\|');
  const lines = [
    DOC_START,
    '',
    '| Variable | Group | Apps | Required | Default | Secret | Description |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const v of variables) {
    const required = v.required ? (v.generated ? 'yes (infra:up)' : 'yes') : 'no';
    const fallback = v.defaultValue === undefined ? '' : `\`${escapePipes(v.defaultValue)}\``;
    lines.push(
      `| \`${v.name}\` | ${v.group} | ${v.apps.join(', ')} | ${required} | ${fallback} | ${v.secret ? 'yes' : ''} | ${escapePipes(v.description)} |`,
    );
  }
  lines.push('', DOC_END);
  return lines.join('\n');
}

/** Replaces the generated block in an existing document (or appends it). */
export function updateDoc(document: string, table: string): string {
  const start = document.indexOf(DOC_START);
  const end = document.indexOf(DOC_END);
  if (start === -1 || end === -1) return `${document.trimEnd()}\n\n${table}\n`;
  return `${document.slice(0, start)}${table}${document.slice(end + DOC_END.length)}`;
}

export function renderEnvExample(variables: readonly DocumentedVariable[]): string {
  const lines = [
    '# Business Finder — environment variables. Copy to .env and fill in what you need.',
    '# Generated by `pnpm env:example` from @bf/config; do not edit by hand. Reference: docs/ENVIRONMENT.md',
    '#',
    '# Precedence: real environment > .env.generated (written by `pnpm infra:up`) > .env > defaults.',
    '# Commented-out lines show the default; uncomment to override.',
    '',
    '# --- Local infrastructure (scripts/infra.mjs) ---',
    '# Shift every host port by this amount (0, 10, …, 70) to run several checkouts side by side.',
    '# BF_PORT_OFFSET=0',
    '# Docker Compose project name; give each checkout its own.',
    '# COMPOSE_PROJECT_NAME=bf',
    '# Local-only credentials of the dev containers (defaults shown).',
    '# POSTGRES_USER=bf',
    '# POSTGRES_PASSWORD=bf_local_only',
    '# POSTGRES_DB=bf',
    '# BF_SITES_RO_PASSWORD=bf_sites_ro_local_only',
  ];
  let group = '';
  for (const v of variables) {
    if (v.group !== group) {
      group = v.group;
      lines.push('', `# --- ${group} ---`);
    }
    const flags = [v.secret ? 'secret' : '', `apps: ${v.apps.join(', ')}`].filter(Boolean).join(' · ');
    lines.push(`# ${v.description} (${flags})`);
    if (v.generated) lines.push(`# ${v.name}=   # written by pnpm infra:up`);
    else if (v.defaultValue !== undefined) lines.push(`# ${v.name}=${v.defaultValue}`);
    else if (v.required) lines.push(`${v.name}=`);
    else lines.push(`# ${v.name}=`);
  }
  return `${lines.join('\n')}\n`;
}
