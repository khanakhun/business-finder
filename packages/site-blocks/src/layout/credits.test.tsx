import { renderToStaticMarkup } from 'react-dom/server';
import { describe, expect, it } from 'vitest';
import { createRenderContext } from '../renderer/resolvers.ts';
import { fixture } from '../test-utils.tsx';
import { Credits, pageAssets } from './credits.tsx';

// Image credits (BF-038): stock photographers linked as Unsplash asks, AI images labelled as illustrations.
describe('credits', () => {
  const salon = fixture('salon-gustavia');
  const home = salon.pages[0];
  if (!home) throw new Error('fixture has pages');
  const heroAssetId = (home.blocks[0]?.props as { imageAssetId?: string } | undefined)?.imageAssetId;

  const withHero = (change: Record<string, unknown>, settings: Record<string, unknown> = {}) => {
    const spec = structuredClone(salon);
    spec.assets = spec.assets.map((asset) => (asset.id === heroAssetId ? { ...asset, ...change } : asset));
    Object.assign(spec.settings, settings);
    return createRenderContext(spec, spec.pages[0] ?? home, 'en');
  };

  it('lists nothing for the business’s own images', () => {
    const ctx = createRenderContext(salon, home, 'en');
    expect(pageAssets(ctx).length).toBeGreaterThan(0);
    expect(renderToStaticMarkup(<Credits ctx={ctx} />)).toBe('');
  });

  it('credits a stock photographer and Unsplash, with the referral parameters', () => {
    const html = renderToStaticMarkup(
      <Credits
        ctx={withHero({
          license: 'stock',
          attribution: 'Photo by Ana Ruiz on Unsplash',
          attributionUrl: 'https://unsplash.com/@ana?utm_source=business_finder&utm_medium=referral',
        })}
      />,
    );
    expect(html).toContain('Photos: ');
    expect(html).toContain(
      'href="https://unsplash.com/@ana?utm_source=business_finder&amp;utm_medium=referral"',
    );
    expect(html).toContain('>Photo by Ana Ruiz</a> on <a');
    expect(html).toContain('href="https://unsplash.com/?utm_source=business_finder&amp;utm_medium=referral"');
  });

  it('labels AI images as illustrations unless the site turns it off', () => {
    expect(renderToStaticMarkup(<Credits ctx={withHero({ license: 'ai_generated' })} />)).toContain(
      'Illustrations generated by AI',
    );
    expect(
      renderToStaticMarkup(<Credits ctx={withHero({ license: 'ai_generated' }, { labelAiImages: false })} />),
    ).toBe('');
  });
});

describe('hotlinked images', () => {
  it('opens the CSP to an allowed stock CDN only when the site uses one, with a srcset at its widths', async () => {
    const { hotlinkOrigins, hotlinkSrcSet } = await import('../renderer/embeds.ts');
    const spec = structuredClone(fixture('salon-gustavia'));
    expect(hotlinkOrigins(spec)).toEqual([]);
    const [first] = spec.assets;
    if (!first) throw new Error('fixture has assets');
    spec.assets[0] = {
      ...first,
      hosting: 'hotlink',
      url: 'https://images.unsplash.com/photo-1?ixid=x&w=1200',
    };
    expect(hotlinkOrigins(spec)).toEqual(['https://images.unsplash.com']);
    spec.assets[0] = { ...first, hosting: 'hotlink', url: 'https://evil.example/x.jpg' };
    expect(hotlinkOrigins(spec)).toEqual([]);
    expect(hotlinkSrcSet('https://images.unsplash.com/photo-1?ixid=x')).toContain(
      'photo-1?ixid=x&w=480 480w',
    );
    expect(hotlinkSrcSet('https://images.unsplash.com/photo-1?ixid=x')).toMatch(/ 1920w$/);
    expect(hotlinkSrcSet('https://evil.example/x.jpg')).toBeUndefined();
  });
});
