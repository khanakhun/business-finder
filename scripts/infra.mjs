#!/usr/bin/env node
// Local infrastructure wrapper around infra/compose/docker-compose.yml.
//
// Usage (via root scripts):
//   pnpm infra:up [--profile scraper|verify|observability|apps]...   start and wait until healthy
//   pnpm infra:down                                              stop all services (keeps volumes)
//   pnpm infra:reset --yes                                       stop and delete all volumes
//   pnpm infra:logs [service...]                                 follow logs
//   pnpm infra:status                                            services, health and URLs
//
// Reads `.env` (real environment wins), applies BF_PORT_OFFSET / COMPOSE_PROJECT_NAME so several checkouts
// can run side by side (docs/conventions/git-workflow.md), and writes `.env.generated` with derived URLs.
// Node built-ins only.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:net';
import { dirname, join } from 'node:path';
import { setTimeout } from 'node:timers/promises';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';
import {
  computePorts,
  derivedEnv,
  PROFILE_SERVICES,
  parseOffset,
  parseProjectName,
  portsFor,
  servicesFor,
  toDotenv,
} from './infra/stack.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const COMPOSE_FILE = join(ROOT, 'infra', 'compose', 'docker-compose.yml');
const GENERATED_FILE = join(ROOT, '.env.generated');
const WAIT_TIMEOUT_S = 180;
const ONE_SHOT_JOBS = ['s3-init'];

function main(argv) {
  const [command = 'status', ...rest] = argv;
  const env = loadEnv();
  const offset = parseOffset(env.BF_PORT_OFFSET);
  const projectName = parseProjectName(env.COMPOSE_PROJECT_NAME);
  const ports = computePorts(offset);
  const profiles = command === 'up' ? parseProfiles(rest) : [];
  const generated = derivedEnv({ ports, env, projectName, offset, profiles });
  const composeEnv = { ...env, ...generated };

  switch (command) {
    case 'up':
      return up(profiles, { composeEnv, generated, ports, projectName });
    case 'down':
      return compose(['--profile', '*', 'down', '--remove-orphans'], composeEnv);
    case 'reset':
      if (!rest.includes('--yes')) {
        console.error('infra:reset deletes all local data volumes. Re-run with --yes to confirm.');
        return 1;
      }
      return compose(['--profile', '*', 'down', '--volumes', '--remove-orphans'], composeEnv);
    case 'logs':
      return compose(['--profile', '*', 'logs', '--follow', '--tail', '200', ...rest], composeEnv);
    case 'ps':
    case 'status':
      compose(['--profile', '*', 'ps', '--all', '--format', 'table {{.Service}}\t{{.Status}}'], composeEnv);
      printUrls(generated);
      return 0;
    default:
      console.error(`Unknown command "${command}". Use up | down | reset | logs | ps | status.`);
      return 1;
  }
}

async function up(profiles, { composeEnv, generated, ports, projectName }) {
  const services = servicesFor(profiles);

  const busy = await findBusyPorts(portsFor(services, ports), publishedPorts(composeEnv));
  if (busy.length > 0) {
    console.error(`Ports already in use (another stack or program is bound to them):`);
    for (const { key, service, port } of busy) console.error(`  ${port}  ${service} (${key})`);
    console.error(`Set BF_PORT_OFFSET=10 (or 20, …, 70) in .env to shift every port, then retry.`);
    return 1;
  }

  writeFileSync(
    GENERATED_FILE,
    toDotenv(generated, 'Generated by `pnpm infra:up` — do not edit; change .env and re-run instead.'),
  );
  console.log(`Wrote ${GENERATED_FILE}`);
  console.log(`Starting project "${projectName}" (${services.join(', ')}) …`);

  const profileArgs = profiles.flatMap((p) => ['--profile', p]);
  const status = compose(
    [...profileArgs, 'up', '--detach', '--build', '--wait', '--wait-timeout', String(WAIT_TIMEOUT_S)],
    composeEnv,
  );
  if (status !== 0) {
    console.error(`\nSome services did not become healthy. Inspect with: pnpm infra:logs <service>`);
    return status;
  }
  // `--wait` covers long-running services only; one-shot jobs must also have finished successfully.
  for (const job of ONE_SHOT_JOBS) {
    const exitCode = await waitForExit(job, composeEnv);
    if (exitCode !== 0) {
      console.error(`\n${job} failed (exit ${exitCode ?? 'timeout'}). Inspect with: pnpm infra:logs ${job}`);
      return 1;
    }
  }
  compose([...profileArgs, 'ps', '--all', '--format', 'table {{.Service}}\t{{.Status}}'], composeEnv);
  printUrls(generated);
  return 0;
}

function parseProfiles(args) {
  const profiles = [];
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--profile') {
      const value = args[++i];
      if (!value) throw new Error(`--profile needs a value: ${Object.keys(PROFILE_SERVICES).join(', ')}`);
      profiles.push(value);
    } else if (arg.startsWith('--profile=')) {
      profiles.push(arg.slice('--profile='.length));
    } else {
      throw new Error(`Unexpected argument "${arg}"`);
    }
  }
  return profiles;
}

/** `.env` overlaid by the real environment (real environment wins). */
function loadEnv() {
  const envFile = join(ROOT, '.env');
  const fileVars = existsSync(envFile) ? parseEnv(readFileSync(envFile, 'utf8')) : {};
  return { ...fileVars, ...process.env };
}

function compose(args, env) {
  const result = spawnSync('docker', ['compose', '--file', COMPOSE_FILE, ...args], {
    env,
    stdio: 'inherit',
  });
  if (result.error) {
    console.error(`Could not run docker compose: ${result.error.message}`);
    return 1;
  }
  return result.status ?? 1;
}

/** Polls a one-shot service until it exits; `compose wait` cannot see containers that already exited. */
async function waitForExit(service, env) {
  const deadline = Date.now() + WAIT_TIMEOUT_S * 1000;
  while (Date.now() < deadline) {
    const [state, exitCode] = composeOutput(
      ['ps', '--all', service, '--format', '{{.State}} {{.ExitCode}}'],
      env,
    )
      .trim()
      .split(' ');
    if (state === 'exited') return Number(exitCode);
    await setTimeout(1000);
  }
  return undefined;
}

function composeOutput(args, env) {
  const result = spawnSync('docker', ['compose', '--file', COMPOSE_FILE, ...args], { env, encoding: 'utf8' });
  return result.status === 0 ? result.stdout : '';
}

/** Host ports already published by this project's containers (so re-running `up` is not a conflict). */
function publishedPorts(env) {
  const ports = new Set();
  const output = composeOutput(['--profile', '*', 'ps', '--format', 'json'], env);
  for (const line of output.split('\n').filter(Boolean)) {
    for (const publisher of JSON.parse(line).Publishers ?? []) {
      if (publisher.PublishedPort) ports.add(publisher.PublishedPort);
    }
  }
  return ports;
}

async function findBusyPorts(candidates, ownPorts) {
  const busy = [];
  for (const candidate of candidates) {
    if (!ownPorts.has(candidate.port) && !(await isFree(candidate.port))) busy.push(candidate);
  }
  return busy;
}

function isFree(port) {
  return new Promise((resolve) => {
    const server = createServer()
      .once('error', () => resolve(false))
      .once('listening', () => server.close(() => resolve(true)))
      .listen(port, '127.0.0.1');
  });
}

function printUrls(env) {
  const rows = [
    ['Postgres', env.DATABASE_URL.replace(/:[^:@/]+@/, ':****@')],
    ['Valkey', env.VALKEY_URL],
    ['S3 API', env.S3_ENDPOINT],
    ['S3 console', `http://127.0.0.1:${env.BF_S3_CONSOLE_PORT}`],
    ['Mailpit UI', `http://127.0.0.1:${env.BF_MAILPIT_UI_PORT}`],
    ['SMTP', env.SMTP_URL],
    ['Maps scraper', `http://127.0.0.1:${env.BF_SCRAPER_PORT}   (profile scraper)`],
    ['Reacher', `http://127.0.0.1:${env.BF_REACHER_PORT}   (profile verify)`],
    ['Jaeger UI', `http://127.0.0.1:${env.BF_JAEGER_UI_PORT}   (profile observability)`],
    ['OTLP (http)', `http://127.0.0.1:${env.BF_OTLP_HTTP_PORT}   (profile observability)`],
  ];
  console.log(`\nProject ${env.COMPOSE_PROJECT_NAME}, port offset ${env.BF_PORT_OFFSET}:`);
  for (const [name, url] of rows) console.log(`  ${name.padEnd(13)} ${url}`);
  console.log(
    `  App ports     web ${env.WEB_PORT} · sites ${env.SITES_PORT} · api ${env.API_PORT} · intel ${env.INTEL_PORT}`,
  );
}

try {
  process.exitCode = await main(process.argv.slice(2));
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
