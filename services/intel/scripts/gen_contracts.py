"""Generates `app/contracts/` from `@bf/contracts` (run through `pnpm contracts:py`).

Inputs (written by `pnpm contracts:jsonschema`):
- `packages/contracts/generated/jsonschema/python/*.json` → one Pydantic v2 module per schema (snake_case);
- `packages/contracts/generated/error-codes.json` → `error_codes.py` (status and title per code).

`--check` exits 1 instead of writing when the committed files are stale (CI). Output is byte-stable: no
timestamps, sorted inputs, ruff-formatted with this project's settings.
"""

import argparse
import difflib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

INTEL = Path(__file__).resolve().parents[1]
REPO = INTEL.parents[1]
SCHEMAS = REPO / "packages/contracts/generated/jsonschema/python"
ERROR_CODES = REPO / "packages/contracts/generated/error-codes.json"
OUT = INTEL / "app/contracts"
SCHEMA_BASE = "https://schemas.business-finder.dev/"
HEADER = "# GENERATED by `pnpm contracts:py` from @bf/contracts — do not edit."


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def prepare(node: object) -> object:
    """Adapts a schema for generation without changing what it accepts in practice.

    - Cross-schema `$ref`s point at their published URL; they become relative files so generation is offline.
    - Zod emits a regex `pattern` next to every `format` (date-time, uuid, email…). The format already maps to
      a typed field (`AwareDatetime`, `UUID`…) and Pydantic rejects `pattern` on non-string types, so it is
      dropped. DECISION(BF-008): Python accepts any UTC offset where Zod requires `Z`; values are compared as
      aware datetimes, and the TypeScript side always sends `Z`.
    """
    if isinstance(node, dict):
        out: dict[str, object] = {}
        for key, value in node.items():
            if key == "$id":
                continue  # A remote $id would make relative refs resolve against the network.
            if key == "pattern" and "format" in node:
                continue
            if key == "$ref" and isinstance(value, str) and value.startswith(SCHEMA_BASE):
                stem, _, fragment = value.removeprefix(SCHEMA_BASE).partition("#")
                local = f"./{snake(stem.removesuffix('.json'))}.json"
                out[key] = f"{local}#{fragment}" if fragment else local
                continue
            out[key] = prepare(value)
        return out
    if isinstance(node, list):
        return [prepare(item) for item in node]
    return node


def error_codes_module(registry: dict[str, object]) -> str:
    type_base = registry["typeBase"]
    codes = registry["codes"]
    if not isinstance(codes, dict):
        raise TypeError("error-codes.json: `codes` must be an object")
    lines = [
        HEADER,
        '"""Error registry (`ERROR_CODES` in packages/contracts/src/errors.ts)."""',
        "",
        "from typing import Final, NamedTuple",
        "",
        "from .problem_details import Code",
        "",
        f"ERROR_TYPE_BASE: Final = {json.dumps(type_base)}",
        "",
        "",
        "class ErrorCodeInfo(NamedTuple):",
        "    status: int",
        "    title: str",
        "",
        "",
        "ERROR_CODES: Final[dict[Code, ErrorCodeInfo]] = {",
    ]
    for code, info in sorted(codes.items()):
        lines.append(f"    Code.{code}: ErrorCodeInfo({info['status']}, {json.dumps(info['title'])}),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(target: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        inputs = Path(tmp) / "schemas"
        inputs.mkdir()
        for schema in sorted(SCHEMAS.glob("*.json")):
            document = prepare(json.loads(schema.read_text()))
            (inputs / f"{snake(schema.stem)}.json").write_text(json.dumps(document, indent=2, sort_keys=True))
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(inputs),
                "--input-file-type",
                "jsonschema",
                "--output",
                str(target),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.13",
                "--use-annotated",
                "--use-standard-collections",
                "--use-union-operator",
                "--field-constraints",
                "--use-schema-description",
                "--use-field-description",
                "--use-title-as-name",
                "--use-double-quotes",
                "--disable-timestamp",
                "--custom-file-header",
                HEADER,
                "--formatters",
                "ruff-format",
            ],
            check=True,
            cwd=INTEL,
        )
    (target / "error_codes.py").write_text(error_codes_module(json.loads(ERROR_CODES.read_text())))
    subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--quiet",
            "--config",
            str(INTEL / "pyproject.toml"),
            str(target),
        ],
        check=True,
        cwd=INTEL,
    )


def tree(root: Path) -> dict[str, str]:
    return {
        str(p.relative_to(root)): p.read_text()
        for p in sorted(root.rglob("*.py"))
        if "__pycache__" not in p.parts
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if app/contracts is out of date")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "contracts"
        generate(fresh)
        expected, current = tree(fresh), tree(OUT) if OUT.exists() else {}
        if args.check:
            if expected == current:
                print(f"Python contracts up to date ({len(expected)} files).")
                return 0
            for name in sorted(expected.keys() | current.keys()):
                diff = difflib.unified_diff(
                    current.get(name, "").splitlines(keepends=True),
                    expected.get(name, "").splitlines(keepends=True),
                    f"app/contracts/{name} (committed)",
                    f"app/contracts/{name} (generated)",
                )
                sys.stdout.writelines(diff)
            print("Python contracts are stale. Run: pnpm contracts:py", file=sys.stderr)
            return 1
        shutil.rmtree(OUT, ignore_errors=True)
        shutil.copytree(fresh, OUT, ignore=shutil.ignore_patterns("__pycache__", ".ruff_cache"))
        print(f"Wrote {len(expected)} files to {OUT.relative_to(REPO)}.")
        return 0


if __name__ == "__main__":
    raise SystemExit(main())
